"""Build players.js for the tactics board from data/players.csv.

Keeps only the fields the board uses, grouped by club, so the page loads quickly.
Run from the repository root:  python3 scripts/build_players.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "players.csv"
OUT = ROOT / "players.js"


def shirt_name(row):
    return (row["shirt_name"] or row["last_name"] or row["name"]).strip()


def main():
    clubs = {}
    with SRC.open(encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            club = clubs.setdefault(row["club"], {"league": row["league"], "players": []})
            club["players"].append([
                int(row["player_id"]),
                shirt_name(row),
                row["name"].strip(),
                row["shirt_number"].strip(),
                row["position"].strip(),
                row["other_positions"].strip(),
                int(row["overall"]),
                row["preferred_foot"].strip()[:1].upper(),  # "L" or "R"
            ])
    for club in clubs.values():
        club["players"].sort(key=lambda p: -p[6])
    data = {
        "fields": ["id", "shirtName", "name", "number", "position", "otherPositions", "overall", "foot"],
        "clubs": dict(sorted(clubs.items())),
    }
    OUT.write_text(
        "// Generated by scripts/build_players.py from data/players.csv. Do not edit by hand.\n"
        "window.PLAYERS_DB = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    total = sum(len(c["players"]) for c in clubs.values())
    print(f"Wrote {OUT.name}: {len(clubs)} clubs, {total} players, {OUT.stat().st_size / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
